/** Convierte el nombre de un grupo en un slug para la URL: minúsculas, sin acentos ni símbolos. */
export function roomSlug(name: string): string {
  return name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60);
}
