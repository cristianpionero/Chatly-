/** Traduce el nombre de una categoría al idioma indicado. */
export function categoryName(lang: string, label: string): string {
  const list = CATEGORY_TRANSLATIONS[lang];
  if (!list) return label;
  const i = CATEGORY_ORDER.indexOf(label as (typeof CATEGORY_ORDER)[number]);
  return i >= 0 ? (list[i] ?? label) : label;
}
